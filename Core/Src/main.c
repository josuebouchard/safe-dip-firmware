/**
 * @brief  The application entry point.
 * @retval int
 */
int main(void)
{

    /* USER CODE BEGIN 1 */

    /* USER CODE END 1 */

    /* MCU Configuration--------------------------------------------------------*/

    /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
    HAL_Init();

    /* USER CODE BEGIN Init */

    /* USER CODE END Init */

    /* Configure the system clock */
    SystemClock_Config();

    /* USER CODE BEGIN SysInit */

    /* USER CODE END SysInit */

    /* Initialize all configured peripherals */
    MX_GPIO_Init();
    MX_USART2_UART_Init();
    MX_SPI1_Init();
    /* USER CODE BEGIN 2 */
    ethernet_W5500_init(); // Initialize W5500

    uint8_t version = getVERSIONR();
    printf("W5500 version register: 0x%02X (expect 0x04)\r\n", version);

    static uint8_t last_state = 0xFF; // force first print

    /* USER CODE END 2 */

    /* Infinite loop */
    /* USER CODE BEGIN WHILE */

    while (1)
    {
        uint8_t ethernet_is_up = getPHYCFGR() & PHYCFGR_LNK_ON;
        uint8_t current_state = getSn_SR(0); // Poll Socket 0's active status register
        uint8_t sn_ir = getSn_IR(0);         // <-- NEW: read interrupt register

        if (current_state != last_state || sn_ir != 0)
        {
            printf("Ethernet up: %s | State: 0x%02X -> 0x%02X | Sn_IR:" BYTE_TO_BINARY_PATTERN
                   "\r\n",
                   ethernet_is_up ? "YES" : "NO", last_state, current_state, BYTE_TO_BINARY(sn_ir));
            last_state = current_state;
        }

        switch (current_state)
        {

        case SOCK_CLOSED:
            if (socket(ECHO_SOCKET, Sn_MR_TCP, ECHO_PORT, 0x00) != ECHO_SOCKET)
            {
                printf("Error creating socket\r\n");
            }
            break;

        case SOCK_INIT:
        {
            int8_t success = listen(ECHO_SOCKET);
            if (success != SOCK_OK)
            {
                printf("ERROR LISTENING: 0x%02X\r\n", success);
            }

            break;
        }

        case SOCK_LISTEN:
            // waiting for an incoming connection; nothing to do
            break;

        case SOCK_ESTABLISHED:
        {
            uint16_t rx_received_size = getSn_RX_RSR(0);

            if (rx_received_size > 0)
            {
                uint8_t data[1024];
                if (rx_received_size > sizeof(data))
                {
                    rx_received_size = sizeof(data);
                }
                int32_t read_bytes = recv(0, data, rx_received_size);
                if (read_bytes > 0)
                {
                    send(0, data, read_bytes);
                }
            }
            break;
        }

        case SOCK_CLOSE_WAIT:
            disconnect(0);
            wiznet_close(0);
            break;

        default:
            break;
        }

        HAL_Delay(200);

        /* USER CODE END WHILE */

        /* USER CODE BEGIN 3 */
    }
    /* USER CODE END 3 */
}

